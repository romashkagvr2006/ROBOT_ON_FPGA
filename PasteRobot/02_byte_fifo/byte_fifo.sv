// =============================================================================
// byte_fifo.sv — очередь байт (FIFO, "первым пришёл — первым ушёл")
// -----------------------------------------------------------------------------
// ЗАЧЕМ НУЖНА
//   Байты из UART приходят тогда, когда их шлёт ПК, а парсер может быть занят:
//   например, ждёт, пока моторы доедут по предыдущей команде. Очередь держит
//   байты, пока парсер их не заберёт. Благодаря ей можно послать несколько строк
//   подряд (например, файлом из Tera Term), и ни один байт не потеряется,
//   пока в очереди есть место (DEPTH байт).
//
// ОТКУДА БЕРЁТ И КУДА ОТДАЁТ
//   Запись:  wr_valid + wr_data  <- uart_rx (rx_valid + rx_data).
//            У приёмника нельзя попросить "подожди", поэтому если очередь полна,
//            байт теряется и поднимается флаг overflow (горит до сброса).
//   Чтение:  rd_valid + rd_data -> cmd_parser, rd_ready <- cmd_parser.
//            Это рукопожатие valid/ready (см. ниже).
//
// РУКОПОЖАТИЕ VALID/READY — так в проекте связаны все модули
//   valid = 1: "у меня есть данные, они лежат на шине data"
//   ready = 1: "я готов их забрать"
//   Передача происходит на том фронте clk, где valid = 1 И ready = 1.
//   Пока ready = 0, отправитель держит valid и data без изменений.
//
// КАК УСТРОЕНА
//   Память mem[] на DEPTH байт (Quartus положит её в блок памяти M9K) и два
//   указателя: wr_ptr — куда писать, rd_ptr — откуда читать. Указатели на 1 бит
//   шире адреса: так "пусто" (указатели равны) отличается от "полно"
//   (отличаются ровно на DEPTH). Байт из памяти заранее переносится в выходной
//   регистр rd_data, поэтому парсер видит его сразу, без лишнего такта.
// =============================================================================
module byte_fifo #(
    parameter int DEPTH = 256   // ёмкость, степень двойки (256 байт = одна строка с запасом)
) (
    input  logic       clk,
    input  logic       rst,        // сброс, активная 1
    // ---- запись (от uart_rx) ----
    input  logic       wr_valid,   // 1 такт: пришёл байт
    input  logic [7:0] wr_data,    // сам байт
    output logic       full,       // очередь полна
    output logic       overflow,   // залипающий флаг: байт пришёл в полную очередь и потерян
    // ---- чтение (к cmd_parser) ----
    output logic       rd_valid,   // в rd_data лежит байт
    output logic [7:0] rd_data,    // самый старый байт очереди
    input  logic       rd_ready    // парсер забирает байт
);
    localparam int ADDR_W = $clog2(DEPTH);

    logic [7:0]      mem [DEPTH];          // сама память
    logic [ADDR_W:0] wr_ptr, rd_ptr;       // указатели на 1 бит шире адреса

    wire [ADDR_W:0] used      = wr_ptr - rd_ptr;     // сколько байт лежит в памяти
    wire            mem_empty = (used == '0);
    assign          full      = (used == (ADDR_W+1)'(DEPTH));

    // Записываем, если байт пришёл и есть место
    wire do_write = wr_valid && !full;
    // Переносим байт из памяти в выходной регистр, если в памяти что-то есть
    // и выходной регистр свободен (или его как раз забирают в этом такте)
    wire do_read  = !mem_empty && (!rd_valid || rd_ready);

    // ---- Память: без сброса, иначе Quartus не сможет сделать её блоком M9K ----
    // мы для памяти используем блоки ОЗУ которые отдельно впаяны в ПЛИс и без сигнала сброса квартус сам сконфигурирует их 
    // за мусор можно не переживать ак как ФИФО буфер будет записывать перед тем как читать следовательно мусор не прочтется
    always_ff @(posedge clk) begin
        if (do_write) mem[wr_ptr[ADDR_W-1:0]] <= wr_data;
        if (do_read)  rd_data                 <= mem[rd_ptr[ADDR_W-1:0]];
    end

    // ---- Указатели и флаги ----
    always_ff @(posedge clk or posedge rst) begin
        if (rst) begin
            wr_ptr   <= '0;
            rd_ptr   <= '0;
            rd_valid <= 1'b0;
            overflow <= 1'b0;
        end else begin
            if (do_write)
                wr_ptr <= wr_ptr + 1'b1;

            if (wr_valid && full)          // байт некуда положить: он потерян
                overflow <= 1'b1;

            if (do_read) begin             // в выходной регистр пришёл новый байт
                rd_ptr   <= rd_ptr + 1'b1;
                rd_valid <= 1'b1;
            end else if (rd_ready) begin   // байт забрали, а нового нет
                rd_valid <= 1'b0;
            end
        end
    end

endmodule
