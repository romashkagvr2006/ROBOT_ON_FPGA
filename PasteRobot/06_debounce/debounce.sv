// =============================================================================
// debounce.sv — синхронизатор и антидребезг для кнопки или концевика
// -----------------------------------------------------------------------------
// ЗАЧЕМ НУЖЕН
//   Механический контакт при нажатии "дребезжит": несколько миллисекунд
//   замыкается и размыкается десятки раз. Без фильтра контроллер увидел бы
//   много ложных нажатий. Кроме того, сигнал с концевика приходит в любой момент,
//   не связанный с clk, поэтому сначала он проходит через синхронизатор.
//
// КАК РАБОТАЕТ
//   1) Два триггера подряд (raw -> sync_0 -> sync_1) — синхронизатор.
//   2) Выход clean меняется, только если вход держит НОВОЕ значение
//      STABLE_CLKS тактов подряд. Любой "дребезг" обнуляет счётчик.
//
//   raw    ‾‾‾‾\_/‾\__/‾\_____________________/‾\_/‾‾‾‾‾‾‾‾‾‾‾
//   clean  ‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾\______________________________/‾‾
//                    |<-STABLE->|                      |<-STABLE->|
//
// ОТКУДА БЕРЁТ И КУДА ОТДАЁТ
//   raw   <- вывод ПЛИС (концевик X, Y или Z), уровень как есть
//   clean -> robot_top инвертирует его при необходимости и отдаёт в
//            motion_ctrl как limit[...] (1 = концевик нажат)
// =============================================================================
module debounce #(
    parameter int   STABLE_CLKS = 100_000,  // сколько тактов вход должен быть стабилен (2 мс при 50 МГц)
    parameter logic RESET_LEVEL = 1'b1      // значение выхода после сброса
) (
    input  logic clk,
    input  logic rst,     // сброс, активная 1
    input  logic raw,     // сырой сигнал с вывода
    output logic clean    // отфильтрованный сигнал
);
    localparam int CNT_W = $clog2(STABLE_CLKS + 1);

    logic             sync_0, sync_1;   // синхронизатор
    logic [CNT_W-1:0] stable_cnt;       // сколько тактов вход отличается от clean

    always_ff @(posedge clk or posedge rst) begin
        if (rst) begin
            sync_0     <= RESET_LEVEL;
            sync_1     <= RESET_LEVEL;
            clean      <= RESET_LEVEL;
            stable_cnt <= '0;
        end else begin
            sync_0 <= raw;
            sync_1 <= sync_0;

            if (sync_1 == clean)
                stable_cnt <= '0;                         // вход совпадает с выходом: ждать нечего
            else if (stable_cnt == CNT_W'(STABLE_CLKS - 1)) begin
                clean      <= sync_1;                     // новое значение продержалось — принимаем
                stable_cnt <= '0;
            end else
                stable_cnt <= stable_cnt + 1'b1;          // новое значение держится, считаем
        end
    end

endmodule
