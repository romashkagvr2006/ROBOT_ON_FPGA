// =============================================================================
// robot_pkg.sv — общий "словарь" всех модулей робота нанесения пасты
// -----------------------------------------------------------------------------
// Пакет подключается в модуль строкой  import robot_pkg::*;
// Здесь описано, на каком языке модули говорят друг с другом:
//   * номера осей X, Y, Z, E (E — поршень шприца, то есть количество пасты);
//   * коды команд G0, G1, G28, M92;
//   * коды ошибок, которые уходят на ПК в ответе "err N";
//   * структура cmd_t — разобранная строка команды. Её собирает парсер
//     (cmd_parser) и передаёт контроллеру движения (motion_ctrl).
//
// Пакет компилируется ПЕРВЫМ, раньше модулей, которые его используют.
// =============================================================================
package robot_pkg;

    // ---- Оси ----------------------------------------------------------------
    // Номер оси — это индекс в массивах has[], value[], k[] и в выходах PUL/DIR.
    localparam int NUM_AXES = 4;
    localparam int AX_X = 0;   // стол по X
    localparam int AX_Y = 1;   // стол по Y
    localparam int AX_Z = 2;   // подъём/опускание шприца
    localparam int AX_E = 3;   // поршень шприца (паста)

    // ---- Числа в командах ---------------------------------------------------
    // Дробей в ПЛИС нет, поэтому все числа хранятся целыми в СОТЫХ долях:
    //   "X20" -> 2000,  "Y30,5" -> 3050,  "E0.25" -> 25,  "E92.2" -> 9220.
    localparam int VALUE_W   = 32;          // разрядность числа (со знаком)
    localparam int VALUE_MAX = 9_999_999;   // 99999,99 — наибольшее число по модулю

    typedef logic signed [VALUE_W-1:0] value_t;

    // ---- Коды команд --------------------------------------------------------
    typedef enum logic [2:0] {
        OP_NONE = 3'd0,   // команды нет (строка не разобрана)
        OP_G0   = 3'd1,   // G0  — переезд без пасты (X, Y или отдельно Z)
        OP_G1   = 3'd2,   // G1  — движение с пастой: X, Y и E одновременно
        OP_G28  = 3'd3,   // G28 — хоминг: оси едут к концевикам, там координата 0
        OP_M92  = 3'd4    // M92 — записать коэффициенты k (импульсов на мм / на мкл)
    } opcode_t;

    // ---- Коды ответа на ПК ---------------------------------------------------
    // 0 -> "ok", остальные -> "err N"
    typedef enum logic [3:0] {
        ERR_NONE    = 4'd0,   // ok
        ERR_UNKNOWN = 4'd1,   // err 1: неизвестная команда (не G0/G1/G28/M92)
        ERR_SYNTAX  = 4'd2,   // err 2: лишний символ, буква не X/Y/Z/E, поле повторено
        ERR_NUMBER  = 4'd3,   // err 3: неверное число (нет цифр, > 2 знаков после
                              //        запятой, больше 99999,99, слишком много импульсов)
        ERR_FIELDS  = 4'd4,   // err 4: недопустимое сочетание полей (G0 с E,
                              //        Z вместе с X/Y, G1 с Z, M92 с k <= 0)
        ERR_LIMIT   = 4'd5,   // err 5: во время движения нажат концевик
        ERR_HOMING  = 4'd6    // err 6: при хоминге концевик так и не нажался
    } err_t;

    // ---- Разобранная команда: парсер -> контроллер движения ----------------
    // Пример: строка "G1 X20 Y30,5 E3" превращается в
    //   opcode = OP_G1, err = ERR_NONE,
    //   has    = 4'b1011  (есть E, Y, X; нет Z),
    //   value[AX_X] = 2000, value[AX_Y] = 3050, value[AX_E] = 300.
    typedef struct packed {
        opcode_t                     opcode;  // что делать
        err_t                        err;     // ERR_NONE, если строка правильная
        logic   [NUM_AXES-1:0]       has;     // has[AX_X] = 1, если в строке было поле X
        value_t [NUM_AXES-1:0]       value;   // value[AX_X] — число после X, в сотых
    } cmd_t;

endpackage
